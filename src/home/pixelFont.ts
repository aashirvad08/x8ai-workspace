export const GLYPH_HEIGHT = 7;

export interface PixelRun {
  /** Lit pixels, in cells from the top left of the whole text. */
  readonly pixels: readonly (readonly [number, number])[];
  readonly width: number;
}

/**
 * The lit pixels of `text`, upper-cased, one blank column between glyphs, and
 * where the text ends. `null` if a character has no glyph, so the caller can
 * show plain text instead.
 */
export function pixelate(text: string, startColumn = 0): PixelRun | null {
  const pixels: [number, number][] = [];
  let column = startColumn;
  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char];
    if (!glyph) return null;
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === "#") pixels.push([column + x, y]);
    });
    column += (glyph[0]?.length ?? 0) + 1;
  }
  return { pixels, width: Math.max(0, column - startColumn - 1) };
}

/** Whether every character of `text` has a glyph. */
export function canPixelate(text: string): boolean {
  return pixelate(text) !== null;
}
